/** Windows user services are logon tasks owned by the current user's SID. */
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { WindowsJob } from '@excitedjs/dreamux-utils';

import type { CommandRunner } from '../platform/command-runner.js';
import { pathExists } from '../platform/fs-errors.js';
import { stateRoot, windowsServiceJobName } from '../platform/paths.js';
import {
  managedServiceCommand,
  managedServiceEnvironment,
  type ServiceInstallAnswers,
} from './environment.js';

const TASK_IDENTITY = `
$user = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
$taskName = 'Dreamux-' + $user
`;
const utilsModuleUrl = pathToFileURL(
  createRequire(import.meta.url).resolve('@excitedjs/dreamux-utils'),
).href;

/** Service management is the only production boundary that invokes PowerShell. */
export function windowsPowerShellEnvironment(
  env: NodeJS.ProcessEnv = process.env,
): NodeJS.ProcessEnv {
  return Object.fromEntries(
    Object.entries(env).filter(([key]) => key.toLowerCase() !== 'psmodulepath'),
  );
}

/** Encoded commands preserve Unicode paths and bypass shell interpolation. */
function windowsPowerShellArgs(script: string): string[] {
  return [
    '-NoLogo',
    '-NoProfile',
    '-NonInteractive',
    '-WindowStyle',
    'Hidden',
    '-EncodedCommand',
    Buffer.from(
      `$ErrorActionPreference = 'Stop'\n$ProgressPreference = 'SilentlyContinue'\n${TASK_IDENTITY}${script}`,
      'utf16le',
    ).toString('base64'),
  ];
}

function psString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

interface WindowsServiceDefinition {
  jobName: string;
  environment: Record<string, string>;
  execStart: string[];
  workingDirectory: string;
  stdoutLog: string;
  stderrLog: string;
}

export function renderWindowsService(
  answers: ServiceInstallAnswers,
  stdoutLog: string,
  stderrLog: string,
): string {
  const definition: WindowsServiceDefinition = {
    jobName: windowsServiceJobName(),
    environment: managedServiceEnvironment(answers),
    execStart: managedServiceCommand(answers, 'serve'),
    workingDirectory: stateRoot(),
    stdoutLog,
    stderrLog,
  };
  return `// Generated by dreamux daemon install. Reinstall to refresh the environment.
import { open } from 'node:fs/promises';
import { SupervisedChild, WindowsJob } from ${JSON.stringify(utilsModuleUrl)};

const definition = ${JSON.stringify(definition, null, 2)};
const serviceJob = await WindowsJob.create(definition.jobName);
await serviceJob.assignCurrentProcess();
const stdout = await open(definition.stdoutLog, 'a');
const stderr = await open(definition.stderrLog, 'a');
const child = new SupervisedChild({
  kind: 'spawn',
  command: definition.execStart[0],
  args: definition.execStart.slice(1),
  options: {
    cwd: definition.workingDirectory,
    env: { ...process.env, ...definition.environment },
    stdio: ['ignore', stdout.fd, stderr.fd],
  },
});
const exited = new Promise((resolve, reject) => {
  child.onExit(resolve);
  child.onError(reject);
});
try {
  await child.start();
  const result = await exited;
  process.exitCode = result.code ?? 1;
} finally {
  await child.stop();
  await Promise.all([stdout.close(), stderr.close()]);
}
`;
}

function parseWindowsService(content: string): WindowsServiceDefinition {
  const json = content.match(/const definition = (\{[\s\S]*?\n\});/);
  if (json === null) {
    throw new Error(
      'Invalid Windows service script; rerun dreamux daemon install',
    );
  }
  return JSON.parse(json[1]) as WindowsServiceDefinition;
}

export async function registerWindowsService(
  unitPath: string,
  runner: CommandRunner,
  answers: ServiceInstallAnswers,
): Promise<void> {
  const actionArgs = `"${unitPath}"`;
  await runner.run(
    'powershell.exe',
    windowsPowerShellArgs(`
$action = New-ScheduledTaskAction -Execute ${psString(answers.nodeBin)} -Argument ${psString(actionArgs)} -WorkingDirectory ${psString(stateRoot())}
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -MultipleInstances IgnoreNew -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
`),
    { dryRun: answers.dryRun, env: windowsPowerShellEnvironment() },
  );
  if (answers.startService) {
    await controlWindowsService('restart', runner, answers.dryRun);
  }
}

export async function controlWindowsService(
  verb: 'start' | 'stop' | 'restart',
  runner: CommandRunner,
  dryRun: boolean,
): Promise<Array<{ command: string; args: string[] }>> {
  const commands =
    verb === 'start' ? [] : await stopWindowsService(runner, dryRun);
  if (verb !== 'stop') {
    const command = {
      command: 'powershell.exe',
      args: windowsPowerShellArgs(
        'Enable-ScheduledTask -TaskName $taskName | Out-Null\nStart-ScheduledTask -TaskName $taskName',
      ),
    };
    await runner.run(command.command, command.args, {
      dryRun,
      env: windowsPowerShellEnvironment(),
    });
    commands.push(command);
  }
  return commands;
}

async function stopWindowsService(
  runner: CommandRunner,
  dryRun: boolean,
): Promise<Array<{ command: string; args: string[] }>> {
  if (dryRun) return [];
  // Acquire the launcher's Job before stopping its owner. If it has not yet
  // created the Job, our empty Job prevents that launch from passing create().
  // Keep the task disabled until the entire kernel-owned group has exited.
  const query = {
    command: 'powershell.exe',
    args: windowsPowerShellArgs(`
$registered = Get-ScheduledTask -TaskPath '\\' | Where-Object TaskName -EQ $taskName
if ($null -eq $registered) { 'null'; exit }
$scheduler = New-Object -ComObject 'Schedule.Service'
$scheduler.Connect()
$task = $scheduler.GetFolder('\\').GetTask($taskName)
$enabled = $task.Enabled
$task.Enabled = $false
$state = @{ enabled = $enabled; launcher = $task.Definition.Actions.Item(1).Arguments }
$state | ConvertTo-Json -Compress
`),
  };
  const state = JSON.parse(
    await runner.capture(query.command, query.args, {
      env: windowsPowerShellEnvironment(),
    }),
  ) as {
    enabled: boolean;
    launcher: string | null;
  } | null;
  if (state === null) return [query];
  const stop = {
    command: 'powershell.exe',
    args: windowsPowerShellArgs(`
$scheduler = New-Object -ComObject 'Schedule.Service'
$scheduler.Connect()
$task = $scheduler.GetFolder('\\').GetTask($taskName)
$task.Stop(0)
`),
  };
  const restore = {
    command: 'powershell.exe',
    args: windowsPowerShellArgs(`
$scheduler = New-Object -ComObject 'Schedule.Service'
$scheduler.Connect()
$scheduler.GetFolder('\\').GetTask($taskName).Enabled = $${state.enabled ? 'true' : 'false'}
`),
  };
  let job: WindowsJob | null = null;
  try {
    if (state.launcher) {
      const definition = parseWindowsService(
        await readFile(state.launcher.replace(/^"|"$/g, ''), 'utf8'),
      );
      job = await WindowsJob.acquire(definition.jobName);
    }
    try {
      await job?.terminate();
    } finally {
      await runner.run(stop.command, stop.args, {
        env: windowsPowerShellEnvironment(),
      });
    }
  } finally {
    // Keep the empty Job reserved until Task Scheduler has stopped the action.
    // A launcher still in its startup phase cannot create a new owned group.
    job?.close();
    await runner.run(restore.command, restore.args, {
      env: windowsPowerShellEnvironment(),
    });
  }
  return [query, stop, restore];
}

export async function unregisterWindowsService(
  runner: CommandRunner,
  dryRun: boolean,
): Promise<void> {
  await stopWindowsService(runner, dryRun);
  await runner.run(
    'powershell.exe',
    windowsPowerShellArgs(`
$task = Get-ScheduledTask -TaskPath '\\' | Where-Object TaskName -EQ $taskName
if ($null -ne $task) {
  Unregister-ScheduledTask -InputObject $task -Confirm:$false
}
`),
    { dryRun, env: windowsPowerShellEnvironment() },
  );
}

export async function windowsServiceStatus(
  unitPath: string,
  runner: CommandRunner,
) {
  const definition = (await pathExists(unitPath))
    ? parseWindowsService(await readFile(unitPath, 'utf8'))
    : null;
  const raw = await runner.capture(
    'powershell.exe',
    windowsPowerShellArgs(`
$task = Get-ScheduledTask -TaskPath '\\' | Where-Object TaskName -EQ $taskName
if ($null -eq $task) { 'null' } else {
  $info = $task | Get-ScheduledTaskInfo
  @{ state = [string]$task.State; enabled = $task.Settings.Enabled; lastResult = $info.LastTaskResult } | ConvertTo-Json -Compress
}
`),
    { env: windowsPowerShellEnvironment() },
  );
  const task = JSON.parse(raw) as {
    state: string;
    enabled: boolean;
    lastResult: number;
  } | null;
  return {
    platform: 'windows' as const,
    unitPath,
    installed: definition !== null || task !== null,
    loaded: task !== null,
    running: task?.state === 'Running',
    enabled: task?.enabled ?? false,
    pid: null,
    detail:
      task === null
        ? 'task not registered'
        : `${task.state}, last result=${task.lastResult}; starts at user logon`,
    environment: definition?.environment ?? null,
    execStart: definition?.execStart ?? null,
  };
}
